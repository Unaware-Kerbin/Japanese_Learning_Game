function shuffleWords(words, seed) {
    const arr = [...words];
    let s = seed || 1;
    for (let i = arr.length - 1; i > 0; i--) {
        s = (s * 1664525 + 1013904223) >>> 0;
        const j = s % (i + 1);
        const swap = arr[i];
        arr[i] = arr[j];
        arr[j] = swap;
    }
    return arr;
}
function mountainLessons(cards) {
    const groups = { N5: [], N4: [], N3: [], N2: [], N1: [] };
    for (const card of cards) {
        if (groups[card.level])
            groups[card.level].push(card);
    }
    const out = [];
    const levels = ['N5', 'N4', 'N3', 'N2', 'N1'];
    for (const level of levels) {
        if (level === 'N1') {
            out.push({
                id: 'n1-yomu',
                band: 'kanji',
                level: 'N1',
                activity: 'type',
                lock: true,
                prompt: 'Write the model sentence. The blank is the whole word, including the okurigana.',
                detail: '本を＿＿。',
                hint: 'I read a book',
                answer: YOMU,
                furigana: 'ほんをよみます',
                say: '本を読みます',
                trap: 'The blank is the whole word, including the okurigana. 読 alone is not 読みます.',
            }, {
                id: 'n1-iu',
                band: 'kanji',
                level: 'N1',
                activity: 'type',
                lock: true,
                prompt: 'Write the model sentence. 言う is read いう.',
                detail: '名前を＿＿。',
                hint: 'say a name',
                answer: IU,
                furigana: 'なまえをいう',
                say: '名前を言う',
                trap: '言 alone fails. 言う passes. 言う is read いう.',
            });
        }
        const bucket = groups[level];
        bucket.forEach((card, index) => {
            const word = card.word || card.ch;
            const blank = card.sentence && word && card.sentence.includes(word) ? card.sentence.replace(word, '＿＿') : '';
            const others = bucket
                .map((item) => item.word)
                .filter((item) => item && item !== word)
                .slice(0, 24);
            const choice = index % 4 === 3 && others.length >= 3;
            const meaning = card.gloss || card.meanings[0] || word;
            const readingNote = `On: ${card.on || '—'}. Kun: ${card.kun || '—'}.`;
            const trap = word !== card.ch
                ? `The blank is the whole word ${word}, not only ${card.ch}. ${readingNote}`
                : `${word} is read ${card.reading}. ${readingNote}`;
            if (choice) {
                out.push({
                    id: `kanji-${level}-${index}`,
                    band: 'kanji',
                    level,
                    activity: 'choice',
                    lock: true,
                    prompt: `Which word means “${meaning}”?`,
                    detail: card.sentenceEn || card.meanings.slice(0, 2).join(', '),
                    hint: meaning,
                    choices: shuffleWords([word, others[0], others[1], others[2]], index + word.length),
                    answer: word,
                    furigana: card.reading,
                    say: word,
                    trap,
                });
                return;
            }
            out.push({
                id: `kanji-${level}-${index}`,
                band: 'kanji',
                level,
                activity: 'type',
                lock: true,
                prompt: blank ? `Write the whole word. ${blank}` : `Write the whole word for “${meaning}.”`,
                detail: card.sentenceEn || card.meanings.slice(0, 2).join(', '),
                hint: meaning,
                answer: word,
                furigana: card.reading,
                say: card.sentence || word,
                trap,
            });
        });
    }
    return out;
}
