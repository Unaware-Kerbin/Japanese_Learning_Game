function rowLessons(rows, band) {
    const out = [];
    for (const row of rows) {
        const id = `${band}-${row.kana[0]}`;
        const target = row.kana[Math.min(1, row.kana.length - 1)];
        out.push({
            id: `${id}-teach`,
            band,
            activity: 'teach',
            prompt: row.kana.join(' '),
            detail: 'This row ends when the round finishes. The next row is already unlocked. A perfect score is not the door.',
            hint: row.hint,
            answer: row.kana.join(''),
            say: row.kana.join(''),
            kana: row.kana,
            trap: 'The missed shape comes back once. The road still opens the next row.',
        });
        out.push({
            id: `${id}-choice`,
            band,
            activity: 'choice',
            prompt: 'Tap the second shape in this row.',
            detail: row.kana.join(' '),
            hint: row.hint,
            choices: row.kana,
            answer: target,
            say: target,
            kana: [target],
            trap: target === 'を'
                ? 'を is said o and typed wo. It is not お.'
                : `That shape was ${target}. The English hint is not the answer.`,
        });
        if (row.word) {
            out.push({
                id: `${id}-word`,
                band,
                activity: 'teach',
                prompt: row.word.text,
                detail: 'Tap a mora when you want the click. The picture is the clue.',
                hint: row.word.en,
                picture: row.word.picture,
                caption: row.word.en,
                answer: row.word.text,
                say: row.word.text,
                kana: [...row.word.text],
                trap: `${row.word.text} is the written word. The English hint is not the answer.`,
            });
        }
    }
    return out;
}
